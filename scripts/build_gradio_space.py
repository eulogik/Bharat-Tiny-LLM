#!/usr/bin/env python3
"""Build Gradio Space files for Bharat-Tiny-LLM v3 into /tmp/bharat-v3-space."""
import os

SPACE = "/tmp/bharat-v3-space"
os.makedirs(SPACE, exist_ok=True)

app_lines = []
app_lines.append('"""')
app_lines.append("Bharat-Tiny-LLM v3 - Bilingual Hindi/Hinglish Chat Demo")
app_lines.append("1.7B params, Q4_K_M quantized, runs offline on edge devices.")
app_lines.append('"""')
app_lines.append("import gradio as gr")
app_lines.append("from huggingface_hub import hf_hub_download")
app_lines.append("from llama_cpp import Llama")
app_lines.append("import os")
app_lines.append("")
app_lines.append('MODEL_REPO = "eulogik/Bharat-Tiny-LLM-v3"')
app_lines.append('MODEL_FILE = "bharat-tiny-llm-v3-q4_k_m.gguf"')
app_lines.append("")
app_lines.append('SYS = ("You are Bharat-Tiny-LLM, a helpful bilingual assistant for Hindi and ")')
app_lines.append('SYS += ("Hinglish. Answer in the same language the user writes. Be concise.")')
app_lines.append("")
app_lines.append('print("Loading model...", flush=True)')
app_lines.append("model_path = hf_hub_download(MODEL_REPO, MODEL_FILE)")
app_lines.append("llm = Llama(")
app_lines.append("    model_path=model_path,")
app_lines.append("    n_ctx=2048,")
app_lines.append("    n_threads=max(2, os.cpu_count() // 2),")
app_lines.append("    verbose=False,")
app_lines.append(")")
app_lines.append('print("Model ready.", flush=True)')
app_lines.append("")
app_lines.append("")
app_lines.append("def build_prompt(message, history):")
app_lines.append('    p = "System: " + SYS + "\\n"')
app_lines.append("    for user_msg, bot_msg in history:")
app_lines.append('        p += "User: " + user_msg + "\\n"')
app_lines.append('        if bot_msg:')
app_lines.append('            p += "Assistant: " + bot_msg + "\\n"')
app_lines.append('    p += "User: " + message + "\\n"')
app_lines.append('    p += "Assistant:"')
app_lines.append("    return p")
app_lines.append("")
app_lines.append("")
app_lines.append("def respond(message, history, temperature, max_tokens):")
app_lines.append("    prompt = build_prompt(message, history)")
app_lines.append("    out = llm(")
app_lines.append("        prompt,")
app_lines.append("        max_tokens=int(max_tokens),")
app_lines.append("        temperature=float(temperature),")
app_lines.append("        top_p=0.9,")
app_lines.append("        repeat_penalty=1.15,")
app_lines.append("        stop=[\"User:\", \"Assistant:\", \"System:\"],")
app_lines.append("        echo=False,")
app_lines.append("    )")
app_lines.append('    text = out["choices"][0]["text"].strip()')
app_lines.append("    history.append((message, text))")
app_lines.append("    return history, \"\"")
app_lines.append("")
app_lines.append("")
app_lines.append('EXAMPLES = [')
app_lines.append('    "नमस्ते, आपका नाम क्या है?",')
app_lines.append('    "भारत की राजधानी क्या है?",')
app_lines.append('    "5 सेब में से 2 खा लिए, बचे कितने?",')
app_lines.append('    "Hinglish mein batao: aaj ka mausam kaisa hai?",')
app_lines.append('    "राम के पास 10 रुपये हैं। उसने 4 खर्च किए। बचे कितने?",')
app_lines.append("]")
app_lines.append("")
app_lines.append("CSS = \"\"\"")
app_lines.append("  .contain { max-width: 760px; margin: auto; }")
app_lines.append("  footer { display: none !important; }")
app_lines.append("\"\"\"")
app_lines.append("")
app_lines.append("with gr.Blocks(css=CSS, title=\"Bharat-Tiny-LLM v3\", theme=gr.themes.Soft()) as demo:")
app_lines.append('    gr.Markdown("# Bharat-Tiny-LLM v3")')
app_lines.append('    gr.Markdown("**Bilingual Hindi / Hinglish edge LLM** - 1.7B params, runs fully offline. Type in Hindi, Hinglish, or English.")')
app_lines.append("    chatbot = gr.Chatbot(height=420, label=\"Chat\", bubble_full_width=False)")
app_lines.append("    with gr.Row():")
app_lines.append("        msg = gr.Textbox(placeholder=\"अपना सवाल यहाँ लिखें / Type your question here...\", scale=4, container=False)")
app_lines.append("        send = gr.Button(\"Send\", scale=1, variant=\"primary\")")
app_lines.append("    with gr.Accordion(\"Settings\", open=False):")
app_lines.append("        with gr.Row():")
app_lines.append("            temp = gr.Slider(0.1, 1.0, value=0.4, label=\"Creativity (temperature)\")")
app_lines.append("            maxtok = gr.Slider(64, 512, value=200, step=32, label=\"Max length\")")
app_lines.append('    gr.Markdown("**Try:**")')
app_lines.append("    gr.Examples(EXAMPLES, msg)")
app_lines.append("    send.click(respond, [msg, chatbot, temp, maxtok], [chatbot, msg])")
app_lines.append("    msg.submit(respond, [msg, chatbot, temp, maxtok], [chatbot, msg])")
app_lines.append("    gr.Markdown(\"---\\nModel: `eulogik/Bharat-Tiny-LLM-v3` (Apache 2.0). Runs offline on edge devices via llama.cpp.\")")
app_lines.append("")
app_lines.append("demo.launch()")

with open(os.path.join(SPACE, "app.py"), "w") as f:
    f.write("\n".join(app_lines) + "\n")

print("wrote app.py:", len(app_lines), "lines")
